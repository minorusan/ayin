#!/bin/zsh
# install-finder-quickaction.sh — install the "Open Ayin here" Finder Quick Action (macOS Service).
#
# After running this, right-click a folder in Finder → Quick Actions → "Open Ayin here" opens a
# Terminal window cd'd into that folder and runs `ayin`. (Folders in the sidebar / the folder
# background also work via the same Services mechanism.)
#
# It's a standard Automator "Quick Action" bundle written to ~/Library/Services, whose single
# Run Shell Script action calls tool/finder-invoke-ayin.sh (this repo) for each selected folder.
# Re-running overwrites cleanly. Uninstall: rm -rf "~/Library/Services/Open Ayin here.workflow".
set -eu

