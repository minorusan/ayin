HELPER="$HERE/finder-invoke-ayin.sh"
[ -f "$HELPER" ] || { print -u2 "missing helper: $HELPER"; exit 1; }
chmod +x "$HELPER"

# Remove the earlier "Invoke Ayin" name so there's only one entry after a rename.
rm -rf "$HOME/Library/Services/Invoke Ayin.workflow"

SERVICE="$HOME/Library/Services/Open Ayin here.workflow"
CONTENTS="$SERVICE/Contents"
mkdir -p "$CONTENTS"

